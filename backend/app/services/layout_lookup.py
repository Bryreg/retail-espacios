PARTES_GEOMETRICAS = tuple(CAMPOS_DE_PARTES)


def _full_code(fixture_code: str, sede: str) -> str:
    """Rebuild the "SEDE-CODE" space code for one fixture.

    Codes generated by the 3D editor already embed the sede, so guard against
    double-prefixing exactly like the frontend does.
    """
    code = fixture_code.upper()
    sede = sede.upper()
    if sede and not code.startswith(f"{sede}-"):
        return f"{sede}-{code}"
    return code


def find_fixture_by_space_code(db: Session, space_code: str) -> dict | None:
    """Return the fixture dict behind a space code, or None if not found.

    Face B of a double gondola shares its parent fixture, so the "-B" suffix is
    stripped before matching.

    **Busca en TODAS las sedes y acepta el código corto pelado**, y las dos cosas
    son a propósito acá: su único llamador es ``is_space_rentable``, que recibe
    un ``Space.code`` ya guardado —de una fila sembrada, de una sede archivada, de
    un mueble borrado del plano después del contrato— y cuya única decisión es
    fallar abierto. Estrecharlo convertiría «no encontré el mueble» en «no es
    comercializable» para espacios que hoy se alquilan sin problema.

    Lo que NO puede entrar por acá es una fila de planilla: ahí el código corto
    sin sede es justamente el agujero —resolvía el mueble y creaba un ``Space``
    nuevo con el código corto, un segundo espacio para el mismo mueble físico—.
    Para eso está ``PlanoIndexado.resolver``, que exige sede y arma el código
    completo con la del fixture.
    """
    code = (space_code or "").strip().upper()
    if not code:
        return None
    # La cara B y la parte (``NEV-03-PU2``, ``GON-05-B-PU1``) son del mismo
    # mueble. Con parte, primero el texto tal cual: un mueble viejo que se
    # llamara literalmente así sigue siendo él mismo.
    partido = partir_codigo(code)
    buscados = ([code] if partido.parte else []) + [partido.base]

    muebles: list[tuple[dict, str, str]] = []
    for snap in db.query(LayoutSnapshot).all():
        try:
            fixtures = json.loads(snap.fixtures_json or "[]")
        except (ValueError, TypeError):
            continue
        if not isinstance(fixtures, list):
            continue
        for fixture in fixtures:
            if not isinstance(fixture, dict):
                continue
            raw = str(fixture.get("code") or "").strip().upper()
            if not raw:
                continue
            sede = str(fixture.get("sede") or snap.sede or "").strip()
            muebles.append((fixture, raw, _full_code(raw, sede)))
    for base in buscados:
        for fixture, raw, completo in muebles:
            if base in (completo, raw):
                return fixture
    return None


#: Tipos que NUNCA son espacio vendible, diga lo que diga la bandera.
#:
#: No son muebles a los que hoy no se les vendió el frente: son **operación de
#: la tienda**. Una columna sostiene el techo; la caja registradora y el
#: mostrador de servicio al cliente son puestos de trabajo del supermercado —
#: ahí se cobra y se atienden reclamos, no se exhibe la marca de un proveedor.
#:
#: Va por TIPO y no por bandera a propósito, y el motivo es retrocompatible al
#: revés de lo que parece: la bandera se estampa al CREAR el mueble, así que
#: una caja guardada antes de que existiera no la tiene, y ``rentable``
#: ausente significa alquilable. O sea que todas las cajas de los planos
#: viejos seguían aceptando un contrato por API. Mirando el tipo, esos planos
#: quedan bien sin migrar una sola fila.
#:
#: Son los tipos con ``alquilable: "nunca"`` del catálogo de muebles
#: (``app/catalogo/muebles.json``, ver ``services/catalogo_muebles.py``): el
#: mismo archivo del que sale ``NUNCA_ALQUILABLE`` de
#: ``frontend/src/types/fixtures.ts``.
NUNCA_ALQUILABLE: frozenset[str] = catalogo_muebles.NUNCA_ALQUILABLE


def es_comercializable(fixture: dict) -> bool:
    """``isRentable`` del frontend, para un fixture ya resuelto.

    Dos preguntas, en orden: primero el TIPO (ver ``NUNCA_ALQUILABLE``),
    después la bandera. La bandera se lee al revés de lo que parece —ausente
    es comercializable— porque un layout guardado antes de que existiera no la
    tiene y todos sus muebles tienen que seguir siendo vendibles.
    """
    if str(fixture.get("type") or "") in NUNCA_ALQUILABLE:
        return False
    return fixture.get("rentable") is not False


def caras_de(fixture: dict) -> int:
    """Cuántas caras vendibles tiene el mueble: 2 es la cara A y la ``-B``.

    Espejo de ``carasDe`` en ``frontend/src/types/espacio.ts``, y es LA
    respuesta a «¿esta góndola tiene cara B?» de este lado: lo que el plano
    ofrece (``espacios_ofrecidos``, el guardarraíl de contratos vivos), la
    importación de contratos del plano, las métricas de la plataforma y
    ``scripts/auditar_desfase.py``.

    Hubo dos reglas. Ésta exigía ``"double"`` escrito mientras Vender ofrecía
    la cara B de una góndola sin ``gondolaType``: se vendía, pero borrar la
    góndola no frenaba por ella y la auditoría la daba por contrato sin
    mueble. Quedó la laxa, que es lo que dibujan los dos editores:

    · ``gondola`` con ``gondolaType`` ``"double"`` o AUSENTE → 2;
    · el tipo legado ``gondola_doble`` de los planos viejos del 2D → 2;
    · cualquier otra cosa (``"wall"``, un mueble que no es góndola) → 1.

    Ausente es ``None``, igual que ``??`` del frontend: un ``""`` escrito no
    cuenta como ausente en ninguno de los dos lados.
    """
    tipo = fixture.get("type")
    if tipo == "gondola_doble":
        return 2
    if tipo != "gondola":
        return 1
    variante = fixture.get("gondolaType")
    return 2 if variante is None or variante == "double" else 1


def por_participacion(fixture: dict) -> bool:
    """¿La cara se vende por participación? Lo dice el mueble
    (``partes.division == "participacion"``), su tipo tiene receta de
    superficie (``tipos[t].superficie`` del catálogo) y es comercializable.
    Una sola forma de dividir: vale para las dos caras de una doble (D5 del
    diseño de participaciones). Es ``porParticipacion`` del navegador.

    ``division_de`` sigue dando ``None`` para ese mueble —una participación no
    es una división física— y ``espacios_de`` da sus caras, no sus
    participaciones: sus números los da el servidor y no tienen tope."""
    partes = fixture.get("partes") if isinstance(fixture, dict) else None
    return (
        isinstance(partes, dict) and partes.get("division") == "participacion"
        and bool((TIPOS.get(tipo_base(str(fixture.get("type") or ""))) or {}).get("superficie"))
        and es_comercializable(fixture)
    )


def caras_por_participacion(fixtures: list, sede: str) -> set[str]:
    """Los códigos COMPLETOS de las caras de los muebles que se venden por
    participación (``NAVE-GON-01``, ``NAVE-GON-01-B``), armados con la sede del
    PLANO —nunca con el campo ``sede`` del mueble—, como
    ``espacios_ofrecidos``. Una participación (``…-PC3``) se ofrece si su cara
    está acá (``ofrece``). Es ``carasPorParticipacion`` del navegador."""
    caras: set[str] = set()
    for f in fixtures or ():
        if not isinstance(f, dict) or not por_participacion(f):
            continue
        code = normalizar(f.get("code"))
        if not code:
            continue
        completo = _full_code(code, normalizar(sede))
        caras.add(completo)
        if caras_de(f) == 2:
            caras.add(f"{completo}-B")
    return caras


#: Lo que contesta ``motivo_para_no_vender``.
NO_COMERCIALIZABLE = "no_comercializable"
SIN_CARA_B = "sin_cara_b"
#: Una parte que el plano no ofrece: la nevera se vende entera, o tiene menos
#: puertas que las que pide el código (``NEV-03-PU4`` en una de tres).
PARTE_INEXISTENTE = "parte_inexistente"
#: Un mueble que nunca se vende entero pero tiene piezas a la venta: la caja
#: con sus bahías de impulso, la columna con su forro. La frase dice cuáles.
SOLO_SUS_PIEZAS = "solo_sus_piezas"
#: Una cara que se vende por participación no se vende entera ni por partes
#: físicas: se carga el porcentaje en el Editor 3D → Distribución.
POR_PARTICIPACION = "por_participacion"

#: fase 2 · I5: la frase para una participación de un tipo de mueble sin receta
#: de superficie (la isla, el impulsador, la batea…): «Cómo se vende» no le
#: ofrece «por participación», así que mandar a elegirlo ahí era un callejón.
#: Es la MISMA frase que ``services/participaciones.TIPO_SIN_PARTICIPACION``
#: (frente A): no se importa de ahí porque ese módulo importa de éste.
TIPO_SIN_PARTICIPACION = "Este tipo de mueble todavía no se vende por participación."


def pide_cara_b_inexistente(fixture: dict, espacio: str) -> bool:
    """¿El código pide la cara B de un mueble que tiene una sola?

    ``espacios_ofrecidos`` no ofrece ``PUN-01-B`` ni la ``-B`` de una góndola
    mural, pero la planilla y el contrato suelto le recortaban el sufijo a
    cualquier mueble y la vendían igual; Supervisar la marcaba enseguida como
    «Contrato sin mueble». La cara B existe cuando ``caras_de`` dice 2: es la
    misma regla para ofrecer, para cuidar y para vender. Vale también para una
    parte de la cara B (``PUN-01-B-PU1``).
    """
    return partir_codigo(espacio).cara == "B" and caras_de(fixture) != 2


def motivo_para_no_vender_parte(fixture: dict, partido: CodigoPartido) -> tuple[str, str] | None:
    """La COMPUERTA: por qué este espacio de este mueble no se puede vender,
    como ``(motivo, frase)``, o ``None`` si se puede.

    La usan la planilla y Vender (``bulk_leases._revisar``) y el contrato suelto
    (``motivo_para_no_vender``): un solo lugar dice qué partes existen. Las
    frases no nombran proveedores ni plata —Vender las lee en vivo, delante del
    proveedor—, y dicen qué hacer.

    · la cara B de un mueble de una cara: no existe, entera ni por partes;
    · un mueble no comercializable: ni la cara ni sus partes;
    · una puerta de una nevera que se vende entera, o con un número de más;
    · un tramo de una góndola que se vende por entrepaños (o al revés): un
      mueble se divide de UNA sola forma;
    · una división que el mueble eligió pero sin la cuenta fijada (la góndola
      por tramos colocada desde una ficha, antes de fijarlos en el panel);
    · la caja o la columna enteras: nunca, pero si tienen piezas configuradas
      se dice cuáles se venden (``SOLO_SUS_PIEZAS``);
    · la cara entera de una cara que se vende por participación
      (``POR_PARTICIPACION``), o una división física de ella; y una
      participación (``…-PC3``) de una cara que NO se vende así. La compuerta
      dice si la participación EXISTE; quién la puede escribir lo dicen los
      caminos;
    · una pieza que su familia no lleva, que el plano no configuró o con un
      número de más (``CAJ-04-BI3`` en una caja de dos). Una pieza se vende
      aunque el mueble no sea comercializable: es lo único que se vende de él.
    """
    # Se nombra con el código que trae quien pregunta (la planilla y el
    # contrato suelto, el completo), como el resto de sus mensajes.
    corto = partido.base
    parte = partido.parte
    if partido.cara == "B" and caras_de(fixture) != 2:
        return SIN_CARA_B, f"«{corto}» tiene una sola cara: no hay cara B que vender."
    if es_pieza(parte):
        return _motivo_de_la_pieza(fixture, corto, partido.cara, parte)
    if not es_comercializable(fixture):
        piezas = piezas_de(fixture)
        if parte is None and piezas:
            clases = list(dict.fromkeys(p.clase for p in piezas))
            nombres = ", ".join(codigo_de_parte(corto, "A", p) for p in piezas)
            una = len(piezas) == 1
            return SOLO_SUS_PIEZAS, (
                f"«{corto}» no se vende: se vende{'' if una else 'n'} {_sus(clases)} ({nombres})."
            )
        lleva = PIEZAS_POR_TIPO.get(tipo_base(str(fixture.get("type") or "")), ())
        frase = f"«{corto}» está marcado como no comercializable: es parte del local."
        if parte is None and lleva:
            # La caja o la columna sin piezas configuradas: lo de siempre, y
            # cómo se pone a la venta lo que sí se vende de ellas.
            return NO_COMERCIALIZABLE, f"{frase} {como_se_venden_sus_piezas(fixture)}"
        return NO_COMERCIALIZABLE, frase
    if por_participacion(fixture):
        if parte is None:
            return POR_PARTICIPACION, (
                f"«{corto}» se vende por participación: cargá el porcentaje en el Editor 3D → "
                "Distribución (podés darle el 100 %)."
            )
        if not es_participacion(parte):
            return PARTE_INEXISTENTE, f"«{corto}» se vende por participación: no hay {parte.sufijo}."
        return None  # una participación de una cara por participación existe
    if es_participacion(parte):
        # fase 2 · I5: un tipo sin receta de superficie (la isla, el
        # impulsador…) no ofrece «por participación» en «Cómo se vende»:
        # mandar a elegirlo ahí era mandar a buscar una opción que no está.
        # La misma frase que `services/participaciones.py`
        # (`TIPO_SIN_PARTICIPACION`), con el código adelante como el resto de
        # los mensajes de esta función.
        if not (TIPOS.get(tipo_base(str(fixture.get("type") or ""))) or {}).get("superficie"):
            return PARTE_INEXISTENTE, f"«{corto}»: {TIPO_SIN_PARTICIPACION}"
        return PARTE_INEXISTENTE, (
            f"«{corto}» no se vende por participación: elegí «por participación» en «Cómo se vende» "
            "del Editor 3D."
        )
    if parte is None:
        return None
    regla = CLASES_DE_PARTE[parte.clase]
    if es_division(parte):
        div = division_de(fixture)
        admite = DIVISIONES_POR_TIPO.get(tipo_base(str(fixture.get("type") or "")), ())
        pedida = (fixture.get("partes") or {}).get("division") if isinstance(fixture.get("partes"), dict) else None
        if parte.clase not in admite:
            # Su familia no se divide así (una punta por tramos).
            formas = " o por ".join(CLASES_DE_PARTE[c]["plural"] for c in admite)
            return PARTE_INEXISTENTE, (
                f"«{corto}» no se vende por {regla['plural']}"
                + (f": se vende entera o por {formas}." if formas else ": se vende entera.")
            )
        if div is not None and div[0] != parte.clase:
            otra = CLASES_DE_PARTE[div[0]]
            return PARTE_INEXISTENTE, (
                f"«{corto}» se vende por {otra['plural']}: un mueble se divide de una sola forma, así "
                f"que no hay {parte.sufijo}."
            )
        if div is None and pedida == parte.clase:
            return PARTE_INEXISTENTE, (
                f"«{corto}» se vende por {regla['plural']}, pero no tiene fijado cuánt"
                f"{concordancia(parte.clase)['o']}s: fijalo en el panel del plano («Cómo se vende»)."
            )
        if div is None:
            return PARTE_INEXISTENTE, (
                f"«{corto}» se vende entera: para venderla por {regla['plural']}, elegí "
                f"«por {regla['plural']}» en el panel del plano."
            )
        if parte.n is None or parte.n > div[1]:
            return PARTE_INEXISTENTE, (
                f"«{corto}» tiene {div[1]} {regla['plural']}: no hay {parte.sufijo}."
            )
    return None


def _sus(clases: list[str]) -> str:
    """«sus bahías de impulso», «su forro» (una pieza única va en singular)."""
    return " y ".join(
        f"su {CLASES_DE_PARTE[c]['singular']}" if CLASES_DE_PARTE[c].get("unico")
        else f"sus {CLASES_DE_PARTE[c]['plural']}"
        for c in clases
    )


def como_se_venden_sus_piezas(fixture: dict) -> str | None:
    """Para un mueble que nunca se vende entero pero cuya familia lleva piezas
    (la caja, la columna): cómo se ponen a la venta, en una frase. ``None``
    si su familia no lleva piezas (el mostrador de servicio al cliente)."""
    lleva = PIEZAS_POR_TIPO.get(tipo_base(str(fixture.get("type") or "")), ())
    if not lleva:
        return None
    como = "; ".join(_como_se_configura(c) for c in lleva)
    return f"{como[:1].upper()}{como[1:]}."


def _como_se_configura(clase: str) -> str:
    """Cómo se pone a la venta una pieza que el plano todavía no tiene."""
    regla = CLASES_DE_PARTE[clase]
    g = concordancia(clase)
    if regla.get("unico"):
        return (f"su {regla['singular']} se vende marcándol{g['o']} en el panel del plano "
                "(«Cómo se vende»)")
    return (f"sus {regla['plural']} se venden un{g['o']} por un{g['o']}, configurándo{g['los']} en el panel "
            "del plano («Cómo se vende»)")


def _motivo_de_la_pieza(fixture: dict, corto: str, cara: str, parte: Parte) -> tuple[str, str] | None:
    """La compuerta de una PIEZA (la bahía de una caja, el forro de una
    columna): que su familia la lleve, que el plano la tenga configurada y que
    el número exista. No pregunta si el mueble es comercializable: la caja no
    lo es nunca, y sus bahías son justamente lo que se vende de ella."""
    regla = CLASES_DE_PARTE[parte.clase]
    g = concordancia(parte.clase)
    lleva = PIEZAS_POR_TIPO.get(tipo_base(str(fixture.get("type") or "")), ())
    if parte.clase not in lleva:
        cual = regla["singular"] if regla.get("unico") else regla["plural"]
        return PARTE_INEXISTENTE, f"«{corto}» no lleva {cual}: no hay {parte.sufijo}."
    if cara == "B":
        # Una pieza no es de una cara: va siempre sin la B (``CAJ-04-BI1``).
        return PARTE_INEXISTENTE, (
            f"{g['el'][:1].upper()}{g['el'][1:]}s {regla['plural']} no son de una cara: se escriben sin la B "
            f"(«{corto}-{parte.sufijo}»)."
        )
    hay = [p for p in piezas_de(fixture) if p.clase == parte.clase]
    if not hay:
        return PARTE_INEXISTENTE, f"«{corto}» no tiene {regla['plural'] if not regla.get('unico') else regla['singular']} " \
            f"en el plano: {_como_se_configura(parte.clase)}."
    if parte not in hay:
        return PARTE_INEXISTENTE, f"«{corto}» tiene {len(hay)} {regla['plural']}: no hay {parte.sufijo}."
    return None


def motivo_para_no_vender(db: Session, space_code: str) -> str | None:
    """Por qué no se le puede colgar un contrato a este código, o ``None``.

    ``NO_COMERCIALIZABLE``: el mueble es operación de la tienda o está marcado
    «no comercializable». ``SIN_CARA_B``: el código es la cara B de un mueble
    de una sola cara (``pide_cara_b_inexistente``). ``PARTE_INEXISTENTE``: una
    parte que el plano no ofrece (``motivo_para_no_vender_parte``).

    Falla abierto, como siempre: un código sin mueble —filas sembradas, un
    mueble borrado del plano después del contrato— se puede vender.
    """
    motivo = por_que_no_se_vende(db, space_code)
    return motivo[0] if motivo else None


def por_que_no_se_vende(db: Session, space_code: str) -> tuple[str, str] | None:
    """``motivo_para_no_vender`` con la frase para la persona."""
    fixture = find_fixture_by_space_code(db, space_code)
    if fixture is None:
        return None
    partido = partir_codigo(space_code)
    if partido.parte is not None and normalizar(space_code).endswith(normalizar(fixture.get("code"))):
        # Resolvió el texto tal cual: un mueble viejo que se llama así. Es su
        # cara entera, no una parte de otro.
        partido = CodigoPartido(normalizar(space_code), "A", None)
    return motivo_para_no_vender_parte(fixture, partido)


def is_space_rentable(db: Session, space_code: str) -> bool:
    """Whether a contract may be attached to this space code.

    Fails open: a space with no matching fixture (seeded demo rows, fixtures
    deleted from the plan after the contract existed) stays rentable. Ver
    ``motivo_para_no_vender``, que además dice por qué.
    """
    return motivo_para_no_vender(db, space_code) is None


# ── El nombre que se DIBUJA, que no es la llave ───────────────────────────────
#
# ATENCIÓN, lector de 2027: esto describe el modelo VIEJO, de dos nombres, y
# sobrevive como RED. Desde la fase 13 el ``code`` es EL nombre y la
# ``nomenclatura`` no se escribe más: ``services/renumeracion.py`` la saca de
# todos los planos y ``choques_nuevos`` (al final de este archivo) impide que
# vuelva a entrar una que pise el nombre de otro. Lo de abajo sigue vivo porque
# una base que no se migró puede tener planos sucios de antes, y porque un
# cliente viejo puede mandar el campo: mientras alguien pueda dibujar dos
# muebles con el mismo rótulo, hay que poder verlo.
#
# En el modelo viejo un mueble tenía dos nombres. El ``code`` es la llave: con él
# se arma ``SEDE-CODE``, que es lo que viaja a ``spaces``, a los archivos, al
# correo del mercaderista y al enlace de montaje. La ``nomenclatura`` era texto
# libre que alguien escribía a mano y que REEMPLAZABA al código **en la
# pantalla**.
#
# Nada obliga a que coincidan, y nada impide que el nombre de un mueble sea el
# código de otro: renumerar una corrida corriendo los números garantiza que cada
# nombre nuevo sea el viejo de otro. Cuando eso pasa, quien lee el plano escribe
# en la planilla un texto que para el servidor es un mueble distinto del que
# estaba mirando, y el contrato cae en el espacio equivocado sin un solo aviso.
#
# Acá vive lo que hace falta para verlo desde el backend: el nombre efectivo de
# un mueble, y si un texto tecleado calza dos muebles a la vez.


def normalizar(texto) -> str:
    """Trim + mayúsculas, igual que ``normalizar`` de ``utils/nomenclatura.ts``.

    Los códigos y los nombres no distinguen mayúsculas ni espacios de sobra: si
    acá se comparara distinto que en el navegador, el plano diría una cosa y el
    servidor otra, que es exactamente el problema que este módulo ataca.
    """
    return ("" if texto is None else str(texto)).strip().upper()


def nombre_de_mueble(fixture: dict) -> str:
    """Cómo se llama un mueble en la pantalla: ``nomenclatura`` o, si no, ``code``.

    Espejo exacto de ``nombreDeMueble`` (``frontend/src/utils/nomenclatura.ts:150``).
    Si las dos reglas se separan, el sistema vuelve a mentir: el backend
    rechazaría una ambigüedad que el plano no dibuja, o dejaría pasar una que sí.
    """
    return str(fixture.get("nomenclatura") or "").strip() or str(fixture.get("code") or "")


def nombre_propio(fixture: dict) -> bool:
    """¿El nombre lo puso una persona, o se heredó del código del sistema?

    Espeja ``nombrePropio`` del frontend, con la comparación normalizada: para
    esto ``imp-08`` y ``IMP-08`` son el mismo nombre, como en todo el resto.
    """
    puesto = str(fixture.get("nomenclatura") or "").strip()
    return bool(puesto) and normalizar(puesto) != normalizar(fixture.get("code"))


class FixtureResuelto:
    """El mueble que resolvió un texto de la planilla, y con qué sede.

    ``codigo`` se arma con la sede **del fixture**, nunca con el texto pelado:
    ahí estaba el segundo agujero. Una fila sin sede resolvía igual contra el
    código corto y creaba un ``Space`` nuevo —``IMP-08`` junto a
    ``CIUDAD JARDIN-IMP-08``— para el mismo mueble físico, cada uno ciego al
    contrato del otro.
    """

    __slots__ = ("fixture", "sede", "codigo", "partido")

    def __init__(self, fixture: dict, sede: str, codigo: str, partido: CodigoPartido | None = None):
        self.fixture = fixture
        self.sede = sede
        self.codigo = codigo
        #: La cara y la parte que pidió el texto (``NEV-03-PU2`` es la puerta 2
        #: de la cara A). ``None`` sólo para quien lo arma a mano.
        self.partido = partido or CodigoPartido(codigo, "A", None)

    @property
    def parte(self) -> Parte | None:
        return self.partido.parte

    @property
    def nombre_dibujado(self) -> str | None:
        """La nomenclatura puesta a mano, o None si el mueble se dibuja con su código."""
        return nombre_de_mueble(self.fixture) if nombre_propio(self.fixture) else None

    def __repr__(self) -> str:  # pragma: no cover - ayuda al depurar un test
        return f"FixtureResuelto({self.codigo!r}, dibujado={self.nombre_dibujado!r})"


class Ambiguedad:
    """Un texto que es el código de un mueble Y el nombre dibujado de otro.

    Las dos mitades del problema, en un solo objeto: ``codigo_tecleado`` es el
    mueble al que el servidor mandaría el contrato, ``codigo_dibujado`` es el que
    la persona estaba mirando en el plano. Nombrar los dos es la diferencia entre
    un rechazo que se entiende y uno que se saltea.

    ``nombre_tecleado`` es cómo dibuja el plano al mueble de ``codigo_tecleado``
    (``None`` si se dibuja con su propio código). El mensaje ofrece los DOS
    caminos y tiene que describir bien cada uno: el mueble de código ``IMP-12``
    se dibuja ``IMP-08``, así que decir de él «el que se dibuja con su propio
    código» mandaría a la persona al mueble equivocado otra vez.
    """

    __slots__ = ("texto", "sede", "codigo_tecleado", "codigo_dibujado", "nombre_tecleado")

    def __init__(self, texto: str, sede: str, codigo_tecleado: str, codigo_dibujado: str,
                 nombre_tecleado: str | None = None):
        self.texto = texto
        self.sede = sede
        self.codigo_tecleado = codigo_tecleado
        self.codigo_dibujado = codigo_dibujado
        self.nombre_tecleado = nombre_tecleado

    def __repr__(self) -> str:  # pragma: no cover
        return f"Ambiguedad({self.texto!r} → {self.codigo_tecleado!r} / {self.codigo_dibujado!r})"


class Colision:
    """El mueble que la fila SÍ resolvió, y el otro con el que se confunde.

    La ambigüedad frena una fila que no se puede resolver. Esto es lo contrario:
    la fila resolvió sin dudas —vino el código completo, o el corto no calzaba
    ningún nombre dibujado— y el contrato va a entrar. Lo que falta decir es que
    el mueble elegido tiene un gemelo de nombre en la misma sede, porque **el
    plano es donde la persona elige** y ahí los dos se ven igual.

    Dos direcciones, que pueden darse las dos a la vez sobre el mismo mueble:

    · ``otro_se_dibuja_con_mi_codigo`` — mi código corto es el nombre que el plano
      le pinta a OTRO. Es la trampa: quien miró la cajita rotulada «IMP-08» y
      siguió el consejo de escribir el código completo llega a ``CIUDAD
      JARDIN-IMP-08``, que es el mueble que NO estaba mirando.
    · ``otro_tiene_por_codigo_mi_nombre`` — el plano me dibuja con un nombre que
      es el código de OTRO. El caso simétrico: el contrato cae donde se pidió,
      pero cualquiera que después lea «IMP-08» va a creer que se contrató el otro.

    Los dos campos son códigos completos: un código corto adentro del aviso
    volvería a ser el texto ambiguo del que estamos tratando de salir.
    """

    __slots__ = ("codigo", "corto", "nombre_dibujado",
                 "otro_se_dibuja_con_mi_codigo", "otro_tiene_por_codigo_mi_nombre")

    def __init__(self, codigo: str, corto: str, nombre_dibujado: str | None,
                 otro_se_dibuja_con_mi_codigo: str | None = None,
                 otro_tiene_por_codigo_mi_nombre: str | None = None):
        self.codigo = codigo
        self.corto = corto
        self.nombre_dibujado = nombre_dibujado
        self.otro_se_dibuja_con_mi_codigo = otro_se_dibuja_con_mi_codigo
        self.otro_tiene_por_codigo_mi_nombre = otro_tiene_por_codigo_mi_nombre

    def __bool__(self) -> bool:
        return bool(self.otro_se_dibuja_con_mi_codigo or self.otro_tiene_por_codigo_mi_nombre)

    def __repr__(self) -> str:  # pragma: no cover
        return (f"Colision({self.codigo!r}, dibujado={self.nombre_dibujado!r}, "
                f"me_dibuja={self.otro_se_dibuja_con_mi_codigo!r}, "
                f"me_nombra={self.otro_tiene_por_codigo_mi_nombre!r})")


def _sin_cara_b(texto: str) -> str:
    """La góndola doble comparte fixture entre sus dos caras; ``-B`` no es parte
    del código del mueble ni de ningún nombre dibujado. Tampoco la parte: la
    puerta 2 (``NEV-03-PU2``) es del mueble ``NEV-03``. Ver ``_sin_sufijos``."""
    return _sin_sufijos(texto)


def _sin_sufijos(texto: str) -> str:
    """El código del mueble, sin la cara B ni la parte: ``GON-05-B-PU1`` →
    ``GON-05``."""
    return partir_codigo(texto).base if texto else texto


def sin_prefijo_de_sede(texto: str, sede: str) -> str:
    """``CIUDAD JARDIN-IMP-08`` + ``CIUDAD JARDIN`` → ``IMP-08``."""
    t = normalizar(texto)
    s = normalizar(sede)
    return t[len(s) + 1:] if s and t.startswith(f"{s}-") else t


class PlanoIndexado:
    """Los muebles de todas las sedes, leídos UNA vez.

    Cada fila de una planilla necesita resolver un código, mirar si es ambiguo y
    —cuando no aparece— averiguar en qué otra sede sí existe. Hacer las tres con
    funciones sueltas serían tres barridos de ``layout_snapshots`` por fila, o
    novecientos en una planilla de trescientas.
    """

    def __init__(self, db: Session):
        self._por_sede: dict[str, list[dict]] = {}
        for snap in db.query(LayoutSnapshot).all():
            try:
                fixtures = json.loads(snap.fixtures_json or "[]")
            except (ValueError, TypeError):
                continue
            if not isinstance(fixtures, list):
                continue
            self._por_sede[normalizar(snap.sede)] = [f for f in fixtures if isinstance(f, dict)]

    # ── Lectura ───────────────────────────────────────────────────────────────

    def de_sede(self, sede: str) -> list[dict]:
        """Los muebles de UNA sede. Acotar no es un detalle: el código corto se
        repite entre tiendas, y buscar en todas devuelve el de la sede
        equivocada."""
        clave = normalizar(sede)
        return self._por_sede.get(clave, []) if clave else []

    def sedes(self) -> list[str]:
        return sorted(self._por_sede)

    # ── Resolver ──────────────────────────────────────────────────────────────

    def resolver(self, sede: str, espacio: str) -> FixtureResuelto | None:
        """El mueble de ESA sede que corresponde al texto, con su código completo.

        Acepta el corto (``IMP-08``) y el completo (``CIUDAD JARDIN-IMP-08``),
        como la planilla que trae la gente. Devuelve el código armado con la sede
        del fixture: si el texto vino corto, el completo lo pone el plano y no la
        fila.
        """
        fixtures = self.de_sede(sede)
        if not fixtures:
            return None
        texto = normalizar(espacio)
        if not texto:
            return None
        # El texto tal cual primero: un mueble podría llamarse literalmente
        # ``GON-01-B`` (o ``X-PU2``), y recortarle la cara o la parte lo
        # dejaría sin resolver. Después, sin la parte y la cara: la puerta 2
        # de ``NEV-03`` es del mueble ``NEV-03``.
        partido = partir_codigo(texto)
        candidatos: list[tuple[str, CodigoPartido | None]] = [(texto, None)]
        if partido.parte is not None or partido.cara == "B":
            candidatos.append((partido.base, partido))

        for buscado, pedido in candidatos:
            for fixture in fixtures:
                raw = normalizar(fixture.get("code"))
                if not raw:
                    continue
                propia = str(fixture.get("sede") or sede or "").strip()
                completo = _full_code(raw, propia)
                if buscado in (raw, completo):
                    if pedido is None:
                        return FixtureResuelto(fixture, normalizar(propia), completo,
                                               CodigoPartido(completo, "A", None))
                    # La cara B de un mueble de una cara no existe: el plano
                    # no la ofrece, y resolverla vendía un espacio que
                    # Supervisar daba enseguida por «Contrato sin mueble».
                    if pedido.cara == "B" and caras_de(fixture) != 2:
                        continue
                    # La parte sí se resuelve aunque el plano no la ofrezca:
                    # la que dice por qué no se vende es la compuerta
                    # (`motivo_para_no_vender_parte`), con una frase que dice
                    # qué hacer.
                    final = CodigoPartido(completo, pedido.cara, pedido.parte)
                    return FixtureResuelto(
                        fixture, normalizar(propia),
                        codigo_de_parte(completo, pedido.cara, pedido.parte), final,
                    )
        return None

    def sin_cara_b(self, sede: str, espacio: str) -> FixtureResuelto | None:
        """El mueble de una sola cara cuya ``-B`` pide el texto, o ``None``.

        Para decir «PUN-01 tiene una sola cara» en vez de un «no hay ningún
        mueble con ese código», que manda a buscar un tipeo que no está.
        """
        texto = normalizar(espacio)
        if partir_codigo(texto).cara != "B" or self.resolver(sede, texto) is not None:
            return None
        base = self.resolver(sede, _sin_sufijos(texto))
        return base if base is not None and caras_de(base.fixture) != 2 else None

    def sedes_con_codigo(self, espacio: str) -> list[str]:
        """En qué sedes existe un mueble con ese código. Para poder decir «no
        existe en NAVE; sí existe en CIUDAD JARDIN» en vez de un «no existe» a
        secas, que manda a buscar un error de tipeo que no está."""
        return [s for s in self.sedes() if self.resolver(s, espacio) is not None]

    # ── El corazón: la ambigüedad ─────────────────────────────────────────────

    def ambiguedad(self, sede: str, espacio: str) -> Ambiguedad | None:
        """¿Ese texto es el código de un mueble Y el nombre dibujado de OTRO?

        Es el caso reproducido: el mueble de código ``IMP-12`` se dibuja
        ``IMP-08`` porque alguien lo renombró a mano, y existe otro cuyo código
        es ``IMP-08``. Quien lee el plano escribe ``IMP-08`` señalando el
        primero; el servidor lo resuelve contra el segundo. Los dos son
        respuestas defendibles, así que la única respuesta honesta es no elegir
        ninguna y pedir que lo desempate una persona.

        **El código completo desempata**, y por eso el mensaje puede pedirlo: los
        nombres dibujados son cortos —es lo que entra en una cajita del plano—,
        así que ``CIUDAD JARDIN-IMP-08`` calza un código y ningún nombre. Escribir
        el completo es decir «hablo de la llave», y ahí no hay nada que dirimir.
        Si alguien llegara a escribir una nomenclatura CON el prefijo de sede,
        vuelve a haber dos candidatos y esto vuelve a rechazar: la regla es la
        misma, no una excepción.
        """
        objetivo = _sin_sufijos(normalizar(espacio))
        if not objetivo:
            return None
        resuelto = self.resolver(sede, espacio)
        if resuelto is None:
            # Sin mueble por código no hay dos candidatos: es un «no existe», y
            # esta fase no resuelve por nomenclatura (en el plano medido las 6 de
            # 6 nomenclaturas son ambiguas: resolver por nombre dejaría seis
            # filas imposibles de cargar y a la persona sin forma de desempatar).
            return None
        for fixture in self.de_sede(sede):
            if fixture is resuelto.fixture:
                continue
            if not nombre_propio(fixture):
                continue
            if normalizar(nombre_de_mueble(fixture)) != objetivo:
                continue
            raw = normalizar(fixture.get("code"))
            propia = str(fixture.get("sede") or sede or "").strip()
            return Ambiguedad(
                texto=objetivo,
                sede=normalizar(sede),
                codigo_tecleado=resuelto.codigo,
                codigo_dibujado=_full_code(raw, propia),
                nombre_tecleado=resuelto.nombre_dibujado,
            )
        return None

    # ── El residuo: la fila que resuelve igual, y entra ───────────────────────

    def colision(self, sede: str, resuelto: FixtureResuelto) -> "Colision | None":
        """El gemelo de nombre del mueble ya resuelto, o ``None`` si no tiene.

        Se pregunta sobre el MUEBLE, no sobre el texto tecleado, y ahí está la
        diferencia con ``ambiguedad``: ``CIUDAD JARDIN-IMP-08`` no es un texto
        ambiguo —calza una llave y ningún nombre— pero el mueble al que lleva sí
        tiene un gemelo, porque otro de la sede se dibuja «IMP-08». Preguntar por
        el texto deja pasar justo el camino que el mensaje de rechazo recomienda.

        Devuelve ``None`` cuando el mueble no choca con nadie, que es el caso de
        casi todas las filas de casi todas las planillas. Es a propósito: un aviso
        que sale en todas las filas entrena a la gente a ignorar los avisos, y el
        que importa se pierde entre ellos.
        """
        sede_fixture = resuelto.sede or sede
        corto = _sin_sufijos(sin_prefijo_de_sede(resuelto.codigo, sede_fixture))
        mi_nombre = normalizar(resuelto.nombre_dibujado or "")

        otro_me_dibuja: str | None = None
        otro_me_nombra: str | None = None
        for fixture in self.de_sede(sede):
            if fixture is resuelto.fixture:
                continue
            raw = normalizar(fixture.get("code"))
            if not raw:
                continue
            propia = str(fixture.get("sede") or sede or "").strip()
            completo = _full_code(raw, propia)
            if otro_me_dibuja is None and corto and nombre_propio(fixture) \
                    and normalizar(nombre_de_mueble(fixture)) == corto:
                otro_me_dibuja = completo
            if otro_me_nombra is None and mi_nombre and raw == mi_nombre:
                otro_me_nombra = completo

        if otro_me_dibuja is None and otro_me_nombra is None:
            return None
        return Colision(
            codigo=resuelto.codigo,
            corto=corto,
            nombre_dibujado=resuelto.nombre_dibujado,
            otro_se_dibuja_con_mi_codigo=otro_me_dibuja,
            otro_tiene_por_codigo_mi_nombre=otro_me_nombra,
        )


def resolver_en_sede(db: Session, sede: str, espacio: str) -> FixtureResuelto | None:
    """Un solo uso. Quien resuelve muchas filas construye un ``PlanoIndexado``."""
    return PlanoIndexado(db).resolver(sede, espacio)


def ambiguedad_de_nombre(db: Session, sede: str, espacio: str) -> Ambiguedad | None:
    return PlanoIndexado(db).ambiguedad(sede, espacio)


# ── Dónde queda el mueble, en palabras ───────────────────────────────────────
#
# El correo de montaje viaja a un celular y se abre en Gmail, que descarta el
# SVG embebido; un PNG obligaría a rasterizar en el servidor —una dependencia
# de imágenes para tres tiendas— y una imagen servida por la app pediría token.
# El plano de verdad vive del otro lado del enlace, en la pantalla. Lo que sí
# llega intacto a cualquier cliente de correo es el texto, así que el correo
# lleva la ubicación escrita y la misma frase que el mercaderista va a ver
# arriba del plano cuando toque el enlace.

#: Muebles que sirven de referencia para alguien parado en la tienda. Son los
#: que cualquiera ubica sin mirar un plano. Salen de ``referencia`` en el
#: catálogo de muebles: las mismas que el minimapa del frontend
#: (``frontend/src/catalogo/minimapa.ts``) dibuja con etiqueta.
_REFERENCIAS: dict[str, str] = catalogo_muebles.REFERENCIAS


def _huella(fixture: dict) -> tuple[float, float]:
    """Ancho y fondo vistos desde arriba, con el giro aplicado.

    ``rotY`` está en RADIANES. Un mueble girado un cuarto de vuelta tiene el
    ancho y el fondo intercambiados; espeja ``footprint2D`` del cliente.
    """
    w = float(fixture.get("w") or 0)
    d = float(fixture.get("d") or 0)
    r = (float(fixture.get("rotY") or 0) % math.pi + math.pi) % math.pi
    return (d, w) if abs(r - math.pi / 2) < 0.15 else (w, d)


def _fixtures_de_sede(db: Session, sede: str) -> list[dict]:
    """Los muebles de UNA sede. Acotar a la sede no es un detalle: la
    nomenclatura corta se repite entre tiendas, y buscar en todas devolvería el
    mueble de la sede equivocada."""
    return PlanoIndexado(db).de_sede(sede)


def describe_location(db: Session, space_code: str, sede: str) -> str | None:
    """Frase corta de ubicación, o None si no hay con qué armarla.

    Devuelve algo como ``"A unos 4 m de las cajas"``. Espeja
    ``describirUbicacion`` de ``frontend/src/components/MiniMapa/MiniMapa.tsx``:
    si las dos frases no coinciden, el mercaderista lee una cosa en el correo y
    otra en la pantalla.

    Solo lee geometría —``cx``, ``cz`` y ``type``—: este correo es el que no
    puede llevar plata, y el fixture crudo trae ``negotiatedValue``.
    """
    code = (space_code or "").strip().upper()
    if not code:
        return None
    # La cara B y la puerta 2 están donde está su mueble.
    partido = partir_codigo(code)
    buscados = ([code] if partido.parte else []) + [partido.base]
    sede_uc = (sede or "").strip().upper()

    fixtures = _fixtures_de_sede(db, sede)
    if not fixtures:
        return None

    target = None
    for base in buscados:
        for fixture in fixtures:
            raw = str(fixture.get("code") or "").strip().upper()
            if not raw:
                continue
            propia = str(fixture.get("sede") or sede_uc or "").strip()
            if base in (_full_code(raw, propia), raw):
                target = fixture
                break
        if target is not None:
            break
    if target is None:
        return None

    try:
        tx = float(target.get("cx"))
        tz = float(target.get("cz"))
        tw, td = _huella(target)
    except (TypeError, ValueError):
        return None

    # De BORDE a borde, no de centro a centro. En NAVE la pared de refrigerados
    # está dibujada como UN mueble de 26 metros de ancho: midiendo al centro, a
    # una punta que está a 3 m de la nevera se le decía "a 8 m", y con esa frase
    # se camina para el lado equivocado. Con los datos reales de esa sede, el
    # centro se equivocaba en 11 de los 19 espacios alquilables.
    mejor: tuple[str, float] | None = None
    for fixture in fixtures:
        frase = _REFERENCIAS.get(str(fixture.get("type") or ""))
        if not frase or fixture is target:
            continue
        try:
            ow, od = _huella(fixture)
            dx = max(0.0, abs(float(fixture.get("cx")) - tx) - (ow + tw) / 2)
            dz = max(0.0, abs(float(fixture.get("cz")) - tz) - (od + td) / 2)
        except (TypeError, ValueError):
            continue
        dist = (dx * dx + dz * dz) ** 0.5
        if mejor is None or dist < mejor[1]:
            mejor = (frase, dist)

    if mejor is None:
        return None
    if mejor[1] < 0.6:
        return f"Pegado a {mejor[0]}"
    return f"A unos {max(1, round(mejor[1]))} m de {mejor[0]}"


# ── El guardarraíl del servidor: no aceptar choques NUEVOS ───────────────────
#
# La fase 12 dejó esto abierto y lo dijo (F7): `PUT /layout/{sede}` aceptaba la
# lista de muebles sin mirar, así que la prohibición de crear un nombre que pisa
# el de otro vivía **sólo en el navegador**. Un guardarraíl que vive en el
# cliente no es del sistema: basta con otra pantalla, un script o una versión
# vieja para saltarlo.
#
# Con un solo nombre la regla es simple —no dos muebles con el mismo nombre en
# la sede— pero no se puede aplicar a secas, porque **un plano que hoy ya está
# mal se tiene que poder guardar**: CIUDAD JARDIN tiene seis nombres que pisan
# el código de otro, y trabar su guardado dejaría al dueño sin poder mover un
# mueble en su propia tienda. Entonces la pregunta no es «¿hay choques?» sino
# «¿este guardado CREA un choque que no venía?», y se responde contra el
# snapshot anterior.
#
# Comparar cuentas y no pares es lo que hace que el intercambio pase: si A se
# llama X y B se llama Y, y el guardado los cruza, la cuenta de X sigue siendo 1
# y la de Y también. Lo mismo una cadena de renombres. Lo que sube la cuenta es
# meter un nombre donde ya había otro, que es exactamente el error que se
# quiere impedir.


def _cuenta_de_nombres(fixtures: list[dict]) -> dict[str, list[str]]:
    """``{nombre dibujado normalizado: [ids de los muebles que lo llevan]}``."""
    cuenta: dict[str, list[str]] = {}
    for f in fixtures:
        if not isinstance(f, dict):
            continue
        nombre = normalizar(nombre_de_mueble(f))
        if not nombre:
            continue
        cuenta.setdefault(nombre, []).append(str(f.get("id") or "?"))
    return cuenta


def _cuenta_de_codigos(fixtures: list[dict]) -> dict[str, list[str]]:
    """Lo mismo, pero por ``code``: la llave con la que se guarda todo.

    Se mira aparte del nombre dibujado porque son dos daños distintos. Dos
    muebles con el mismo nombre no se distinguen en el plano; dos muebles con el
    mismo **código** comparten contratos, archivos y correos de montaje, que es
    peor y sigue siendo posible mientras exista un segundo nombre que lo tape.
    """
    cuenta: dict[str, list[str]] = {}
    for f in fixtures:
        if not isinstance(f, dict):
            continue
        code = normalizar(f.get("code"))
        if not code:
            continue
        cuenta.setdefault(code, []).append(str(f.get("id") or "?"))
    return cuenta


def _como_se_ven(previas: list[dict], nuevas: list[dict]) -> dict[str, str]:
    """``{id del mueble: cómo lo ve la persona en la pantalla}``.

    El mensaje del rechazo tiene que nombrar a los muebles con algo que exista
    para quien lo lee. El ``id`` (``imp9``, ``pun8``) es una llave interna: no
    aparece en el plano, ni en el panel, ni en un contrato, ni en el papel — y
    nombrar con él es tan útil como no nombrar.

    Lo que la persona tiene delante es el plano **guardado**, así que se los
    nombra por el nombre que ese plano dibuja hoy, con su rótulo al lado para
    poder encontrarlos («el que hoy se llama «PUN-08» (Punta de Góndola)»). Un
    mueble que este guardado agrega todavía no está en ninguna pantalla, y se
    dice así.

    Se nombra por el ``code`` y NO por ``nombre_de_mueble``. Desde que el
    código es el nombre, las pantallas dibujan el ``code`` y nada más; en el
    único plano donde los dos difieren —uno que todavía arrastra una
    ``nomenclatura`` vieja, o sea producción antes de renumerar— nombrar por
    ``nomenclatura`` deja el mensaje **al revés**: le dice a la persona un
    nombre que ninguna pantalla dibuja, y le da el nombre que sí ve al mueble
    equivocado. Se nombra por lo que se ve.
    """
    como: dict[str, str] = {}
    for fixtures, en_pantalla in ((nuevas, False), (previas, True)):
        for f in fixtures:
            if not isinstance(f, dict):
                continue
            ident = str(f.get("id") or "")
            if not ident:
                continue
            nombre = normalizar(str(f.get("code") or ""))
            rotulo = str(f.get("label") or f.get("type") or "").strip()
            texto = f"«{nombre}»" if nombre else "un mueble sin nombre"
            if rotulo:
                texto += f" ({rotulo})"
            como[ident] = (
                f"el que hoy se llama {texto}" if en_pantalla
                else f"el que se agrega en este guardado, {texto}"
            )
    return como


def _y(frases: list[str]) -> str:
    """``a``, ``a y b``, ``a, b y c``: se lee como lo diría una persona.

    Vive acá y lo usa también ``services/renumeracion.py``: dos listas de cosas
    escritas para una persona no tienen por qué separarse con comas distintas.
    """
    if len(frases) < 2:
        return frases[0] if frases else ""
    return ", ".join(frases[:-1]) + " y " + frases[-1]


def _nombrados(ids: list[str], como: dict[str, str]) -> str:
    """Los muebles del choque, nombrados por lo que se ve y en orden estable.

    Dos muebles que hoy se dibujan IGUAL —un choque que ya venía— se describen
    con la misma frase, y repetirla palabra por palabra se lee como un error de
    la aplicación. Se dice una vez: la cuenta ya va en el encabezado del mensaje.
    """
    sueltos = (como.get(i) or "otro mueble de la sede, sin identidad en el plano"
               for i in ids)
    return _y(list(dict.fromkeys(sorted(sueltos))))


def choques_nuevos(previas: list[dict], nuevas: list[dict]) -> list[str]:
    """Los choques que este guardado CREA, en castellano. Vacío = se guarda.

    Un choque preexistente —o uno que se guarda igual de mal que antes— no
    aparece acá: es la regla que no se negocia, «el plano que ya está mal se
    abre, se mira y se guarda».

    Las frases salen listas para mostrar y **nombran a los muebles por su
    nombre**, que es lo único que la persona ve. Ver ``_como_se_ven``.
    """
    antes = _cuenta_de_nombres(previas)
    despues = _cuenta_de_nombres(nuevas)
    por_nombre = [
        (nombre, ids)
        for nombre, ids in sorted(despues.items())
        if len(ids) >= 2 and len(ids) > len(antes.get(nombre, []))
    ]
    ya_dicho = {nombre for nombre, _ in por_nombre}

    antes_c = _cuenta_de_codigos(previas)
    despues_c = _cuenta_de_codigos(nuevas)
    por_codigo = [
        (code, ids)
        for code, ids in sorted(despues_c.items())
        if code not in ya_dicho
        and len(ids) >= 2
        and len(ids) > len(antes_c.get(code, []))
    ]

    # Primero se decide si hay algo que decir y recién después se arma con qué
    # nombrarlo: esto corre en CADA guardado, y el caso normal —no hay choque
    # nuevo— no tiene por qué pagar un recorrido más de los muebles del plano.
    if not por_nombre and not por_codigo:
        return []
    como = _como_se_ven(previas, nuevas)

    return [
        f"«{nombre}» quedaría como nombre de {len(ids)} muebles de la sede: "
        f"{_nombrados(ids, como)}. Dos muebles con el mismo nombre no se "
        "distinguen en el plano ni en un contrato."
        for nombre, ids in por_nombre
    ] + [
        f"El código «{code}» quedaría en {len(ids)} muebles de la sede: "
        f"{_nombrados(ids, como)}. Dos muebles con el mismo código son dos "
        "espacios compartiendo contratos, archivos y correos de montaje."
        for code, ids in por_codigo
    ]


# ─── Medidas que no se pueden dibujar (fase 2 · I5) ──────────────────────────
#
# ``PUT /layout`` recibe ``fixtures: list[Any]`` y no miraba las medidas. La
# superficie se cuida sola (``superficie.MEDIDA_MAXIMA``/``MAX_VANOS``), pero el
# 3D no: con un ancho de 1e6 y un módulo de 1e-9 ``vanosDeCorrido`` pedía un
# arreglo de mil billones de módulos y colgaba la pestaña de quien abriera el
# plano; con un ancho infinito, ``RangeError``. Medido: ``PUT`` con
# ``w=1e308, modulo=1e-9`` → 200.
#
# La misma política que ``choques_nuevos``: sólo lo que ESTE guardado crea o
# cambia, por ``id``. Un plano que ya traía una medida rota se sigue abriendo y
# guardando (moviendo otro mueble, o ese mismo); sólo se frena escribir una
# medida imposible nueva. El primer guardado de una sede no se compara con nada
# y entra, como siempre.

#: Las medidas que se miran, en el primer nivel del mueble.
_MEDIDAS = ("w", "d", "h")
_NOMBRE_DE_MEDIDA = {"w": "el ancho", "d": "el fondo", "h": "el alto"}
#: Las claves cuyo cambio hace que el mueble se vuelva a mirar entero.
_MEDIDAS_QUE_SE_MIRAN = (*_MEDIDAS, "modulo", "entrepanos")
#: Entrepaños por cara: la familia que más lleva admite 6 (``geometria`` del
#: catálogo); 50 es un número roto, no una góndola alta.
MAX_ENTREPANOS = 50


def _cifra(x: float) -> str:
    """Un número para la frase, a la colombiana: «0,001», «3.600», «1e+308»."""
    if not math.isfinite(x):
        return "infinito" if x > 0 else "menos infinito" if x < 0 else "sin número"
    if x != 0 and (abs(x) >= 1e7 or abs(x) < 1e-3):
        return f"{x:.3g}".replace(".", ",")
    if float(x).is_integer():
        return f"{int(x):,}".replace(",", ".")
    texto = f"{x:,.3f}".rstrip("0").rstrip(".")
    return texto.replace(",", "§").replace(".", ",").replace("§", ".")


def _flotante(x) -> float | None:
    """El número como ``float``, o ``None`` si no es un número (un texto, un
    booleano). Un entero que no entra en un ``float`` (``10**400`` escrito en
    el JSON) es infinito: ``float()`` se caería con ``OverflowError``."""
    if not isinstance(x, (int, float)) or isinstance(x, bool):
        return None
    try:
        return float(x)
    except OverflowError:
        return math.inf if x > 0 else -math.inf


def _problemas_de_medidas(f: dict) -> list[str]:
    """Lo imposible de UN mueble, en frases cortas (sin el nombre)."""
    from app.services.superficie import MAX_VANOS, MEDIDA_MAXIMA

    malas: list[str] = []
    for clave in _MEDIDAS:
        if f.get(clave) is None:
            continue
        x = _flotante(f[clave])
        if x is None:
            malas.append(f"{_NOMBRE_DE_MEDIDA[clave]} no es un número")
        elif not math.isfinite(x) or x <= 0 or x > MEDIDA_MAXIMA:
            malas.append(
                f"{_NOMBRE_DE_MEDIDA[clave]} de {_cifra(x)} m no se puede dibujar "
                f"(va de más de 0 a {_cifra(MEDIDA_MAXIMA)} m)"
            )
    if f.get("modulo") is not None:
        modulo = _flotante(f["modulo"])
        if modulo is None or not math.isfinite(modulo) or modulo <= 0:
            cual = "un texto" if modulo is None else f"{_cifra(modulo)} m"
            malas.append(f"un módulo de {cual} no se puede dibujar")
        else:
            w = _flotante(f.get("w"))
            if w is not None and math.isfinite(w) and 0 < w <= MEDIDA_MAXIMA:
                cuenta = w / modulo
                n = round(cuenta) if math.isfinite(cuenta) else None
                if n is None or n > MAX_VANOS:
                    cuantos = _cifra(float(n)) if n is not None else "incontables"
                    malas.append(
                        f"con un módulo de {_cifra(modulo)} m saldrían {cuantos} módulos; "
                        f"el tope es {MAX_VANOS}"
                    )
    if f.get("entrepanos") is not None:
        e = _flotante(f["entrepanos"])
        if e is None:
            malas.append("los entrepaños no son un número")
        elif not math.isfinite(e) or not e.is_integer() or not 0 <= e <= MAX_ENTREPANOS:
            malas.append(f"{_cifra(e)} entrepaños no se pueden dibujar (van de 0 a {MAX_ENTREPANOS}, enteros)")
    return malas


def _misma(a, b) -> bool:
    """¿La misma medida? Un ``NaN`` guardado (``json`` lo lee y lo escribe)
    es igual a sí mismo: si no, el plano que ya lo traía no se podría volver a
    guardar tal cual."""
    if isinstance(a, float) and isinstance(b, float) and math.isnan(a) and math.isnan(b):
        return True
    return a == b


def medidas_imposibles(previas: list[dict], nuevas: list[dict]) -> list[str]:
    """Las frases de los muebles a los que ESTE guardado les pone (o les deja,
    al cambiarlas) medidas que no se pueden dibujar. Vacío = se guarda.

    Un mueble se mira si es nuevo (un ``id`` que el plano guardado no tiene, o
    sin ``id``) o si cambió alguna de ``_MEDIDAS_QUE_SE_MIRAN``. Imposible:
    ``w``/``d``/``h`` que no son un número finito, ≤ 0 o > ``MEDIDA_MAXIMA``;
    un ``modulo`` que no es finito o ≤ 0, o con el que ``round(w / modulo)``
    pasa de ``MAX_VANOS``; ``entrepanos`` que no es un entero de 0 a
    ``MAX_ENTREPANOS``. Una clave ausente o ``null`` no se juzga (el navegador
    usa la cuenta de siempre). Las frases nombran al mueble por su código, que
    es lo que la persona ve."""
    previos = {f.get("id"): f for f in previas if isinstance(f, dict) and f.get("id")}
    frases: list[str] = []
    for f in nuevas:
        if not isinstance(f, dict):
            continue
        previo = previos.get(f.get("id")) if f.get("id") else None
        if previo is not None and all(_misma(previo.get(k), f.get(k)) for k in _MEDIDAS_QUE_SE_MIRAN):
            continue
        malas = _problemas_de_medidas(f)
        if malas:
            nombre = normalizar(f.get("code")) or "un mueble sin código"
            frases.append(f"{nombre}: {'; '.join(malas)}.")
    return sorted(frases)


# ─── La tercera puerta: sacar de circulación algo que está vendido ────────────
#
# La auditoría encontró que TODA edición del plano que retira un espacio de la
# venta deja su contrato vivo en la base, por tres puertas distintas:
#
#   1. borrar el mueble;
#   2. pasar una góndola de doble a simple — la cara B desaparece;
#   3. marcarlo «no comercializable».
#
# Ninguna avisaba, porque el plano NO le escribe a la base: ese camino no
# existe. El contrato quedaba vivo, sin nada en pantalla que lo mostrara, y
# aparecía meses después al intentar vender: «está libre y el sistema dice que
# está ocupado». Así se reportó el caso que originó todo esto.
#
# Se comprueba acá, al guardar el plano, y no en cada botón de borrar: es el
# único lugar por el que pasan las tres puertas y los cuatro caminos —el panel
# del 2D, el del 3D, la tecla Supr y el borrado en lote—. Un guardarraíl que hay
# que acordarse de poner en cada botón es un guardarraíl que se va a olvidar.


def espacios_de(fixture: dict, sede: str) -> list[str]:
    """Los códigos COMPLETOS que un mueble pone a la venta: sus caras y sus
    partes (``NAVE-NEV-03``, ``NAVE-NEV-03-PU1``…). Es ``espaciosDe`` de
    ``utils/partes.ts``, con los mismos casos (``casos/partes.json``). Un
    mueble sin ``partes.division`` da sus caras, como siempre. Uno que no es
    comercializable no da sus caras, pero sí sus PIEZAS configuradas (las
    bahías de una caja, el forro de una columna): es lo que se vende de él."""
    if not isinstance(fixture, dict):
        return []
    code = (fixture.get("code") or "").strip().upper()
    if not code:
        return []
    completo = _full_code(code, str(fixture.get("sede") or sede or ""))
    comercializable = es_comercializable(fixture)
    caras = caras_de(fixture)
    fuera = []
    if comercializable:
        fuera.append(completo)
        if caras == 2:
            fuera.append(f"{completo}-B")
    for cara, parte in partes_de(fixture, caras, comercializable):
        fuera.append(codigo_de_parte(completo, cara, parte))
    return fuera


def espacios_ofrecidos(fixtures: list[dict], sede: str) -> set[str]:
    """Los códigos COMPLETOS que este plano pone a la venta hoy.

    Una góndola doble son dos espacios: ``NAVE-GON-60`` y ``NAVE-GON-60-B``
    (``caras_de``). Una nevera que se vende por puertas, además, sus puertas:
    ``NAVE-NEV-03-PU1``… (``espacios_de``). Un mueble no comercializable NO
    está — y ése es justamente uno de los casos que hay que encontrar.

    Con la sede del PLANO, no la del mueble: es la que usaba siempre, y la
    respuesta de un plano viejo tiene que ser la misma.
    """
    ofrecidos: set[str] = set()
    for fixture in fixtures:
        if not isinstance(fixture, dict):
            continue
        ofrecidos.update(espacios_de({**fixture, "sede": sede}, sede))
    return ofrecidos


def ofrece(ofrecidos: set[str], caras_pc: set[str], codigo: str) -> bool:
    """¿El plano pone a la venta este código COMPLETO? Una participación
    (``NAVE-GON-01-PC3``) no está en ``espacios_ofrecidos`` —sus números no
    tienen tope—: se ofrece si su cara se vende por participación
    (``caras_pc``, de ``caras_por_participacion``). Todo lo demás, si está en
    ``ofrecidos``. Lo usan el guardarraíl de contratos vivos, la auditoría de
    la pantalla (``utils/auditoriaDesfase.ts``) y ``scripts/auditar_desfase.py``.

    El texto tal cual primero, como ``PlanoIndexado.resolver``: un mueble de
    antes del token que ya se llamaba ``GON-07-PC1`` (riesgo R1 del diseño;
    un nombre nuevo así no entra) es su cara entera, y está en ``ofrecidos``.
    Sin esto, retirarlo del plano dejaba su contrato vivo sin frenar."""
    c = normalizar(codigo)
    if c in ofrecidos:
        return True
    p = partir_codigo(c)
    return es_participacion(p.parte) and codigo_de_parte(p.base, p.cara, None) in caras_pc


def _vivos_de_la_sede(db: Session, sede: str) -> list[tuple]:
    """``[(lease, space)]`` de los contratos vivos de la sede (no cancelados y
    que terminan hoy o después) MÁS sus reservas vivas de una cara entera o de
    una parte, como ``ReservaComoContrato`` (§8 de
    ``docs/rediseno/vender-api.md``): sacar de circulación algo reservado se
    frena igual que algo vendido."""
    from app.fechas import hoy as hoy_en_colombia
    from app.models.models import Space, SpaceLease
    from app.models.vender import ReservaDeEspacio

    hoy = hoy_en_colombia()
    s = sede.strip().upper()
    vivos = (
        db.query(SpaceLease, Space)
        .join(Space, Space.id == SpaceLease.space_id)
        .filter(Space.sede == s, SpaceLease.is_active.is_(True), SpaceLease.end_date >= hoy)
        .all()
    )
    reservas = (
        db.query(ReservaDeEspacio, Space)
        .join(Space, Space.id == ReservaDeEspacio.space_id)
        .filter(Space.sede == s, ReservaDeEspacio.estado == "viva", ReservaDeEspacio.caduca >= hoy,
                ReservaDeEspacio.hasta >= hoy)
        .all()
    )
    return list(vivos) + [
        (ReservaComoContrato(id=-r.id, reserva_id=r.id, start_date=r.desde, end_date=r.hasta, supplier=r.supplier),
         space)
        for r, space in reservas
    ]


def _que_tiene(lease) -> str:
    """«un contrato» o «una reserva», para las frases de quien administra."""
    return "una reserva" if getattr(lease, "es_reserva", False) else "un contrato"


def contratos_que_quedarian_sin_mueble(
    db: Session, sede: str, previas: list[dict], nuevas: list[dict],
) -> list[str]:
    """Las frases de los contratos vivos que este guardado dejaría huérfanos.

    **Sólo lo que este guardado CREA**, igual que ``choques_nuevos`` y por la
    misma razón: una sede que YA tiene un contrato sin mueble —las que había
    antes de que esto existiera— quedaría imposible de guardar para siempre, y
    la regla que no se negocia es que un plano roto se abre, se mira, se mueve
    y se guarda. Sólo se frena el espacio que este guardado retira.

    Un plano que entra por primera vez no se compara con nada y pasa.

    La plata no entra en las frases. Para decidir alcanza con el proveedor y
    hasta cuándo va; el valor no ayuda a nadie a elegir y es un dato menos
    viajando.

    Una participación (``GON-01-PC3``) queda perdida si su cara se vendía por
    participación antes de este guardado y deja de venderse así (``ofrece``):
    sacar la división, cambiar el tipo, marcarlo no comercializable, borrar el
    mueble o pasar la doble a mural.
    """
    if not previas:
        return []
    ofrecidos_antes, ofrecidos_despues = espacios_ofrecidos(previas, sede), espacios_ofrecidos(nuevas, sede)
    pc_antes, pc_despues = caras_por_participacion(previas, sede), caras_por_participacion(nuevas, sede)
    if not (ofrecidos_antes - ofrecidos_despues) and not (pc_antes - pc_despues):
        return []

    vivos = _vivos_de_la_sede(db, sede)

    frases = []
    for lease, space in vivos:
        # Por la forma completa: una fila guardada sin la sede (`NEV-03-PU3`)
        # es el mismo espacio que el plano ofrece como `NAVE-NEV-03-PU3`.
        completo = _full_code(sin_prefijo_de_sede(normalizar(space.code), sede), sede)
        if not ofrece(ofrecidos_antes, pc_antes, completo) or ofrece(ofrecidos_despues, pc_despues, completo):
            continue
        # Se nombra por el código CORTO: es el que está en el plano y en la
        # cartelería de la tienda, y es el que la persona acaba de tocar.
        corto = sin_prefijo_de_sede(completo, sede)
        quien = lease.supplier.name if lease.supplier else "sin proveedor"
        if getattr(lease, "es_reserva", False):
            frases.append(
                f"«{corto}» tiene una reserva de {quien} hasta el "
                f"{lease.end_date.isoformat()}. Cancelala primero, o volvé a poner "
                f"el mueble: si se va del plano, la reserva queda viva y sin nada "
                f"que la muestre."
            )
            continue
        frases.append(
            f"«{corto}» tiene un contrato de {quien} hasta el "
            f"{lease.end_date.isoformat()}. Cancelalo primero, o volvé a poner "
            f"el mueble: si se va del plano, el contrato queda vivo y sin nada "
            f"que lo muestre."
        )
    return sorted(frases)


# ─── Vender por partes: lo que choca, lo que se movería, lo que no se nombra ──
#
# Una puerta vendida (``NEV-03-PU2``) es un espacio más, con su fila en
# ``spaces``. La regla de la dueña —la nevera entera o por puertas, nunca las
# dos en las mismas fechas— se decide por los códigos (``partes.chocan``), así
# que todos los caminos que crean un contrato preguntan lo mismo acá.


def _escapar_like(texto: str) -> str:
    return texto.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")


def forma_canonica(db: Session, sede: str, codigo: str) -> str | None:
    """El código con que se guarda el espacio de un mueble que se vende por
    partes: con la sede del mueble, en mayúsculas y sin espacios
    (``NAVE-NEV-03-PU2``, ``NAVE-NEV-03``), como lo arma la planilla
    (``PlanoIndexado.resolver``).

    ``None`` si el texto no es una parte ni la cara de un mueble del plano que
    se vende por partes: ahí no se exige nada, como siempre (un espacio
    sembrado sin sede, una cara de un mueble que se vende entero).

    Una cara que se vende por participación, o que tiene participaciones
    (filas ``…-PC<n>`` de esa cara en ``spaces``, aunque ya no se venda así),
    también exige la forma completa: ``GON-01`` y ``NAVE-GON-01`` dan claves de
    candado distintas (``candado.clave_de_candado``), y el contrato de la cara
    entera tiene que tomar la misma que sus participaciones.

    Para qué: la regla «entera o por partes, nunca las dos» compara CÓDIGOS
    (``contratos_que_chocan``). El contrato suelto aceptaba ``NEV-03-PU2`` sin
    sede, o con un espacio adelante, porque la compuerta resuelve el mueble por
    el código pelado; pero la otra forma no veía ese contrato, y la nevera se
    vendía entera a uno y por puertas a otro en las mismas fechas.
    """
    plano = PlanoIndexado(db)
    sedes = [normalizar(sede)] if normalizar(sede) else []
    sedes += [s for s in plano.sedes_con_codigo(codigo) if s not in sedes]
    for s in sedes:
        r = plano.resolver(s, codigo)
        if r is None:
            continue
        f = r.fixture
        if r.parte is not None or partes_de(f, caras_de(f), es_comercializable(f)) or por_participacion(f) \
                or _tiene_participaciones(db, s, r.codigo):
            return r.codigo
        return None
    return None


def _tiene_participaciones(db: Session, sede: str, cara: str) -> bool:
    """¿Hay alguna fila de ``spaces`` que sea una participación de esa cara
    (``NAVE-GON-01-PC3`` de ``NAVE-GON-01``; también la forma corta de esa
    sede y la archivada, ``…-PC3#12``)? Una sola consulta por prefijo. Una
    participación se crea con su fila y no se borra nunca, así que esto ve
    toda cara que tuvo términos de participación."""
    from sqlalchemy import func, or_
    from app.models.models import Space

    cara = normalizar(cara)
    s = normalizar(sede)
    formas = {cara} | ({sin_prefijo_de_sede(cara, s)} if s else set())
    guardado = func.upper(func.trim(Space.code))
    filas = (
        db.query(Space.code, Space.sede)
        .filter(or_(*[guardado.like(f"{_escapar_like(c)}-PC%", escape="\\") for c in sorted(formas)]))
        .all()
    )
    for code, sede_fila in filas:
        bruto = normalizar(code).split("#", 1)[0]
        # La forma corta es de ESTA sede sólo si su fila lo dice (o no dice ninguna).
        if s and not bruto.startswith(f"{s}-") and normalizar(sede_fila) not in ("", s):
            continue
        p = partir_codigo(_full_code(sin_prefijo_de_sede(bruto, s), s) if s else bruto)
        if es_participacion(p.parte) and codigo_de_parte(p.base, p.cara, None) == cara:
            return True
    return False


@dataclass
class ReservaComoContrato:
    """Una reserva viva de una cara entera o de una parte
    (``models/vender.ReservaDeEspacio``), con la forma de un contrato para
    quien pregunta qué choca: lo reservado cuenta como ocupado en sus fechas
    (``docs/rediseno/vender-api.md`` §8). ``id`` es NEGATIVO (``-reserva.id``):
    nunca se confunde con el de un contrato. Nadie lee de acá quién reservó:
    delante del proveedor una cara reservada por otro se ve tomada y nada más."""
    id: int
    reserva_id: int
    start_date: object
    end_date: object
    supplier: object = None
    is_active: bool = True
    es_reserva: bool = True


def contratos_que_chocan(db: Session, codigo: str, desde, hasta, space_id: int | None = None,
                         sede: str | None = None, excluir_reserva: int | None = None,
                         excluir_lease: int | None = None) -> list[tuple]:
    """Los contratos vivos (no cancelados) que no dejan vender ``codigo`` entre
    ``desde`` y ``hasta``, ambos inclusive: el del mismo espacio, el de la cara
    entera si es una puerta, y los de sus puertas si es la cara entera.

    ``[(lease, space, partido)]``, en orden de fecha. Una sola consulta: el
    código mismo, la cara, y lo que empieza con ``<cara>-`` (filtrado después
    con ``chocan``: la ``-B`` de la cara A no choca, ``GON-050`` no calza).
    ``space_id``: el espacio mismo, por su id, aunque su código esté guardado
    con otras mayúsculas (el contrato suelto preguntaba así).

    Los códigos guardados se comparan sin mayúsculas ni espacios de los
    costados, y con ``sede`` también en su forma corta —``NEV-03-PU2`` de una
    fila de esa sede es ``NAVE-NEV-03-PU2``—: un contrato guardado con otra
    escritura no puede quedar ciego a la regla «entera o por partes, nunca las
    dos». El contrato suelto ya exige la forma completa (``forma_canonica``);
    esto cuida las filas que ya estaban.

    Las reservas VIVAS de una cara entera o de una parte (§8 de
    ``docs/rediseno/vender-api.md``) también chocan, como
    ``ReservaComoContrato``: así la planilla, el contrato suelto, Vender, la
    importación del plano y la capacidad de una cara por participación
    (``fisicos_de``) las cuentan sin saber que existen. ``excluir_reserva``:
    la que se está confirmando, que no choca consigo misma.

    ``excluir_lease``: el contrato que se está EDITANDO (``services/
    editar_contrato.py``, sólo esa ruta), que no choca consigo mismo. Cualquier
    otro contrato —también otro del mismo proveedor en la misma cara— choca
    igual.
    """
    from sqlalchemy import func, or_
    from app.fechas import hoy as hoy_en_colombia
    from app.models.models import Space, SpaceLease
    from app.models.vender import ReservaDeEspacio

    s = normalizar(sede)

    def completo(texto) -> str:
        t = normalizar(texto)
        return _full_code(sin_prefijo_de_sede(t, s), s) if s else t

    codigo = completo(codigo)
    yo = partir_codigo(codigo)
    cara = yo.cara_entera
    caras = {cara} | ({sin_prefijo_de_sede(cara, s)} if s else set())
    codigos = {codigo} | ({sin_prefijo_de_sede(codigo, s)} if s else set())
    guardado = func.upper(func.trim(Space.code))
    filas = (
        db.query(SpaceLease, Space)
        .join(Space, Space.id == SpaceLease.space_id)
        .filter(
            SpaceLease.is_active.is_(True),
            SpaceLease.start_date <= hasta,
            SpaceLease.end_date >= desde,
            SpaceLease.id != (excluir_lease if excluir_lease is not None else -1),
            or_(guardado.in_(sorted(codigos | caras)),
                *[guardado.like(f"{_escapar_like(c)}-%", escape="\\") for c in sorted(caras)],
                Space.id == (space_id if space_id is not None else -1)),
        )
        .all()
    )
    donde = or_(guardado.in_(sorted(codigos | caras)),
                *[guardado.like(f"{_escapar_like(c)}-%", escape="\\") for c in sorted(caras)],
                Space.id == (space_id if space_id is not None else -1))
    reservas = (
        db.query(ReservaDeEspacio, Space)
        .join(Space, Space.id == ReservaDeEspacio.space_id)
        .filter(
            ReservaDeEspacio.estado == "viva",
            ReservaDeEspacio.caduca >= hoy_en_colombia(),
            ReservaDeEspacio.desde <= hasta,
            ReservaDeEspacio.hasta >= desde,
            ReservaDeEspacio.id != (excluir_reserva if excluir_reserva is not None else -1),
            donde,
        )
        .all()
    )
    filas = list(filas) + [
        (ReservaComoContrato(id=-r.id, reserva_id=r.id, start_date=r.desde, end_date=r.hasta, supplier=r.supplier),
         space)
        for r, space in reservas
    ]
    fuera = []
    for lease, space in filas:
        bruto = normalizar(space.code)
        # La forma corta es de ESTA sede sólo si su fila lo dice (o no dice
        # ninguna): `PUN-01` se repite en las tres tiendas.
        if s and not bruto.startswith(f"{s}-") and normalizar(space.sede) not in ("", s) \
                and space.id != space_id:
            continue
        otro = partir_codigo(completo(bruto))
        if space.id == space_id or completo(bruto) == codigo or chocan(yo, otro):
            fuera.append((lease, space, otro))
    fuera.sort(key=lambda x: (x[0].start_date, x[0].id))
    return fuera


def frase_tomada(otro_codigo: str, lease, sede: str = "") -> str:
    """La frase de un choque DELANTE DEL PROVEEDOR (Vender, ``?validar=1`` y el
    guardado de ``POST /api/contratos/vender``): una sola, para cualquier
    choque. No dice si lo otro es un contrato o una reserva, ni de quién, ni
    cuántos: que está tomado y en qué fechas, que es lo que hay que mover. La
    planilla y el contrato suelto (administración) siguen con
    ``frase_de_choque``."""
    from app.fechas import dia_corto
    return (f"«{sin_prefijo_de_sede(otro_codigo, sede)}» está tomado del {dia_corto(lease.start_date)} "
            f"al {dia_corto(lease.end_date)}: ajustá las fechas.")


def frase_de_choque(codigo: str, otro_codigo: str, lease) -> str:
    """Por qué no entra, sin decir de quién es lo otro: Vender lee esto en vivo,
    delante del proveedor. Las fechas sí: son las que hay que mover."""
    codigo, otro_codigo = normalizar(codigo), normalizar(otro_codigo)
    fechas = f"del {lease.start_date} al {lease.end_date}"
    if codigo == otro_codigo:
        if getattr(lease, "es_reserva", False):
            # Una reserva viva: tomado, sin decir que es una reserva ni de quién
            # (§8 de docs/rediseno/vender-api.md).
            return f"«{codigo}» está tomado {fechas}: ajustá las fechas."
        return f"«{codigo}» ya tiene un contrato {fechas}. Cancelalo primero o ajustá las fechas."
    yo, otro = partir_codigo(codigo), partir_codigo(otro_codigo)
    if yo.parte is not None and otro.parte is None:
        regla = CLASES_DE_PARTE[yo.parte.clase]
        return f"«{otro_codigo}» está vendida entera {fechas}: en esas fechas no se vende por {regla['plural']}."
    if yo.parte is None and otro.parte is not None:
        regla = CLASES_DE_PARTE[otro.parte.clase]
        g = concordancia(otro.parte.clase)
        return (
            f"«{otro_codigo}» ({texto_de_parte(otro.parte).lower()}) está vendid{g['o']} {fechas}: en esas "
            f"fechas «{codigo}» no se vende entera; {g['los']} otr{g['o']}s {regla['plural']}, sí."
        )
    if otro.parte is not None:
        # Dos divisiones de clases distintas de la misma cara: el tramo 2 y el
        # entrepaño 3 comparten una repisa. Un mueble se divide de una forma.
        g = concordancia(otro.parte.clase)
        return (
            f"«{otro_codigo}» ({texto_de_parte(otro.parte).lower()}) está vendid{g['o']} {fechas} y se pisa "
            f"con «{codigo}»: un mueble se divide de una sola forma."
        )
    return f"«{otro_codigo}» está vendida {fechas} y se pisa con «{codigo}»."


def nombres_reservados_nuevos(previas: list[dict], nuevas: list[dict]) -> list[str]:
    """Los muebles que ESTE guardado nombra como el código de una parte o de la
    cara B (``GON-01-B``, ``NEV-03-PU2``, ``GON-01-TR2``): su código se leería
    como una parte de otro mueble. Sólo los que el guardado agrega —un plano
    viejo con un nombre así se sigue guardando—, comparando contra el plano
    anterior, como ``choques_nuevos``."""
    ya = {normalizar(f.get("code")) for f in previas if isinstance(f, dict)}
    malos = sorted({
        normalizar(f.get("code")) for f in nuevas
        if isinstance(f, dict) and normalizar(f.get("code")) not in ya and termina_reservado(f.get("code"))
    })
    return [
        f"«{c}» termina como el código de una parte o de la cara B (-B, -PU2…): ese código se "
        "confundiría con el de una parte de otro mueble. Elegí otro nombre."
        for c in malos
    ]


def partes_que_se_moverian(db: Session, sede: str, previas: list[dict], nuevas: list[dict]) -> list[str]:
    """Las frases de las partes vendidas que este guardado MOVERÍA de lugar.

    ``contratos_que_quedarian_sin_mueble`` ya frena la parte vendida que
    desaparece (bajar de 3 a 2 puertas con la 3 vendida, sacar la división).
    Esto frena la que sigue existiendo pero en otro lugar: con la puerta 1
    vendida, pasar de 3 a 2 puertas convierte la «puerta 1» en otra hoja, y lo
    que firmó el proveedor ya no es lo que se monta.

    Por CÓDIGO del mueble y no por ``id``: borrar ``NEV-03`` y dibujar otra
    ``NEV-03`` con 4 puertas también se frena. Sólo lo que ESTE guardado cambia
    (un plano que ya venía desfasado se guarda), y el caso normal —nada cambia—
    no consulta la base.
    """
    if not previas:
        return []

    def por_codigo(fixtures: list[dict]) -> dict[str, dict]:
        fuera: dict[str, dict] = {}
        for f in fixtures:
            if not isinstance(f, dict):
                continue
            code = normalizar(f.get("code"))
            if code:
                fuera[_full_code(code, sede)] = f
        return fuera

    antes, despues = por_codigo(previas), por_codigo(nuevas)
    cambiadas: dict[str, tuple[dict, dict]] = {}
    for codigo, f in despues.items():
        prev = antes.get(codigo)
        if prev is None:
            continue
        fa, fd = firma_de_partes(prev), firma_de_partes(f)
        if fa != fd:
            cambiadas[codigo] = (fa, fd)
    if not cambiadas:
        return []

    vivos = _vivos_de_la_sede(db, sede)
    frases = []
    for lease, space in vivos:
        p = partir_codigo(space.code or "")
        # Por la forma completa: una parte guardada sin la sede (`NEV-03-PU1`,
        # de antes de que el contrato suelto la exigiera) también se mueve.
        mueble = _full_code(sin_prefijo_de_sede(p.base, sede), sede)
        # Una participación no tiene un lugar físico que moverse: si su cara
        # deja de venderse así, la frena `contratos_que_quedarian_sin_mueble`.
        if p.parte is None or es_participacion(p.parte) or mueble not in cambiadas:
            continue
        fa, fd = cambiadas[mueble]
        n_antes, n_despues = fa.get(p.parte.clase), fd.get(p.parte.clase)
        # Sólo lo que se ofrecía: una parte vendida sin que el plano la
        # ofreciera (un desfase de antes) no se mueve por darle lugar.
        if n_antes is None or n_antes == n_despues:
            continue
        regla = CLASES_DE_PARTE[p.parte.clase]
        g = concordancia(p.parte.clase)
        corto_mueble = sin_prefijo_de_sede(p.base, sede)
        def cuantas(n: int) -> str:
            return f"{n} {regla['singular'] if n == 1 else regla['plural']}"

        # Los entrepaños se cuentan con la base (el EN1): con 4 entrepaños en
        # el panel se venden 5. Se dice, para que «de 5 a 4» no se lea como un
        # error cuando el campo pasó de 4 a 3.
        con_la_base = " (contando la base)" if regla.get("base") else ""
        cambio = (
            f"no puede pasar de {n_antes} a {cuantas(n_despues)}{con_la_base}" if n_despues is not None
            else f"no puede quedarse sin {regla['plural']}" if es_pieza(p.parte)
            else f"no puede dejar de venderse por {regla['plural']}"
        )
        quien = lease.supplier.name if lease.supplier else "sin proveedor"
        frases.append(
            f"«{sin_prefijo_de_sede(space.code or '', sede)}» tiene {_que_tiene(lease)} de {quien} hasta el "
            f"{lease.end_date.isoformat()}: con {g['un']} {regla['singular']} vendid{g['o']}, «{corto_mueble}» {cambio}"
            f" ({g['el']} {regla['singular']} vendid{g['o']} quedaría en otro lugar). Esperá a que termine o cancelalo primero."
        )
    return sorted(frases)
